const API_KEY = process.env.USER_GEMINI_API_KEY || process.env.GEMINI_API_KEY || "";
const BASE_URL = process.env.USER_GEMINI_BASE_URL || "https://generativelanguage.googleapis.com/v1beta";
const MODEL = process.env.USER_GEMINI_MODEL || "gemini-3.6-flash";

export function isLive() {
  return !!API_KEY;
}

export function currentModel() {
  return isLive() ? MODEL : "localboost-sim-v1";
}

async function callGemini({ system, prompt, json = false }) {
  const body = {
    contents: [
      {
        role: "user",
        parts: [{ text: system ? `${system}\n\n${prompt}` : prompt }],
      },
    ],
    generationConfig: {
      temperature: 0.7,
      ...(json ? { responseMimeType: "application/json" } : {}),
    },
  };
  const res = await fetch(
    `${BASE_URL}/models/${MODEL}:generateContent`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key": API_KEY,
      },
      body: JSON.stringify(body),
    },
  );
  if (!res.ok) {
    const errText = await res.text().catch(() => "");
    throw new Error(`Gemini API error ${res.status}: ${errText.slice(0, 200)}`);
  }
  const data = await res.json();
  const text =
    data?.candidates?.[0]?.content?.parts?.map((p) => p.text || "").join("") || "";
  return text.trim();
}

export async function generate({ system = "", prompt = "", context = {}, json = false, forceSim = false }) {
  if (!isLive() || forceSim) {
    return { text: simulate(context), simulated: true, model: currentModel() };
  }
  try {
    const text = await callGemini({ system, prompt, json });
    return { text, simulated: false, model: currentModel() };
  } catch (err) {
    console.warn("[llm] fallback to simulation:", err.message);
    return { text: simulate(context), simulated: true, model: currentModel() };
  }
}

