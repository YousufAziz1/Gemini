function pick(arr, seed) {
  let i = 0;
  for (const c of String(seed)) i = (i * 31 + c.charCodeAt(0)) % arr.length;
  return arr[Math.abs(i) % arr.length];
}

function hash(str) {
  let h = 0;
  for (const c of String(str)) h = (h * 31 + c.charCodeAt(0)) | 0;
  return String(h);
}

export function simulate(context = {}) {
  const kind = context.kind || "generic";
  const seed = hash(JSON.stringify(context));
  const biz = context.businessName || "your business";
  const platform = context.platform || "Facebook";
  const replyText = pick(SUPPORT_REPLIES, seed);

  switch (kind) {
    case "content":
      return `[${platform}] ${pick(CONTENT_SNIPPETS, seed)}`.replace(
        "Fresh batch out now",
        `Fresh batch out now at ${biz}`,
      );
    case "social":
      return pick(SOCIAL_SNIPPETS, seed);
    case "support":
      return replyText;
    case "report":
      return REPORT_TEMPLATE(biz);
    case "plan":
      return PLAN_TEMPLATE(biz);
    case "billing":
      return JSON.stringify({
        amount: context.amount || 499,
        due_date: context.dueDate || "2026-09-01",
        memo: `Monthly AI Agency subscription for ${biz}`,
      });
    case "analytics":
      return JSON.stringify({
        recommendation: `Increase posting frequency on ${platform} to 4x/week.`,
        projected_revenue: 1480,
      });
    case "onboard":
      return JSON.stringify({
        tagline: `${biz} — where the neighborhood feels like home.`,
        recommended_plan: "Essentials",
      });
    default:
      return `Understood. I will handle this for ${biz} now.`;
  }
}
